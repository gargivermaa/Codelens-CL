"""
Semantic code chunking with Tree-sitter.

Splits Python source into complete syntactic units (functions, methods,
classes) instead of fixed-size character windows, so every chunk that is
later embedded and retrieved is a meaningful piece of code.

Chunking rules
  * Top-level and conditionally-defined functions -> type "function".
  * Functions defined inside a class -> type "method".
  * Classes -> type "class" (full text), AND each method is also its own chunk,
    so retrieval can match either the whole class or one method.
  * Functions nested inside other functions are NOT separate chunks; they stay
    part of their parent function's text.
  * Decorators are part of the chunk (@app.post(...), @login_required, ...).

Size handling (no source code is ever dropped)
  * A unit whose text fits MAX_EMBED_BYTES is one chunk (part_count == 1).
  * A larger function/method is split into consecutive "parts" along
    statement boundaries found in the syntax tree. Every source line of the
    unit belongs to exactly one part.
  * A larger class is split the same way, but only over the lines that are
    NOT inside its methods/nested classes (header, docstring, attributes):
    the methods are already their own chunks, so nothing is lost and nothing
    is embedded twice.
  * A single source line longer than the budget (e.g. a huge literal) is cut
    into byte windows on UTF-8 character boundaries, again losing nothing.

The byte budget exists because the embedding model limits input length; see
app/core/embedder.py. Day 7 scope: parsing only, no network or database.
"""
import argparse
import logging
import os
import re
import textwrap
from collections import Counter
from dataclasses import asdict, dataclass
from pathlib import Path

import tree_sitter_python as tspython
from tree_sitter import Language, Node, Parser

logger = logging.getLogger("codelens.chunker")

PY_LANGUAGE = Language(tspython.language())

# gemini-embedding-001 accepts at most 2048 input tokens. Every token covers at
# least one UTF-8 byte, so an input of N bytes is at most N tokens: a byte
# budget below 2048 guarantees the token limit without needing a tokenizer.
MAX_EMBED_BYTES = 1800

# Split parts are embedded with a one-line header ("# file :: name (part i/n)")
# so a part keeps its identity; reserve room for it inside MAX_EMBED_BYTES.
PART_HEADER_RESERVE = 200
MAX_PART_BYTES = MAX_EMBED_BYTES - PART_HEADER_RESERVE

# Larger files are almost always generated/vendored code, not worth indexing.
MAX_FILE_BYTES = 1_000_000

IGNORED_DIRS = frozenset({
    ".git", ".hg", ".svn", "venv", ".venv", "env", "node_modules", "__pycache__",
    "build", "dist", "site-packages", ".tox", ".mypy_cache", ".pytest_cache",
    ".ruff_cache", "migrations", "tests", "test",
    # vendored / third-party code is not the repository's own code
    "vendor", "vendored", "_vendor", "third_party", "thirdparty", "external",
    # local backups are not production modules
    "backup", "backups", ".backup", "old", "bak",
})

# Backup / copy files people keep next to real modules, e.g. "embedder_backup.py",
# "embedder_old.py", "embedder copy.py", "embedder (1).py", "embedder.bak.py".
_BACKUP_FILE = re.compile(
    r"[_.\- ](?:backup|bak|old|orig|copy)(?:[_.\- ]?\d*)?\.py$|\(\d+\)\.py$|^backup",
    re.IGNORECASE,
)

# Generated code (protobuf/grpc stubs) - reviewing or retrieving it is noise.
_GENERATED_SUFFIXES = ("_pb2.py", "_pb2_grpc.py", "_pb2.pyi")
_GENERATED_MARKERS = (b"do not edit", b"autogenerated", b"auto-generated", b"generated by")

_DEFINITIONS = ("function_definition", "class_definition")

# Node types whose first line is a safe place to start a new part.
_STATEMENT_TYPES = frozenset({
    "expression_statement", "return_statement", "if_statement", "for_statement",
    "while_statement", "try_statement", "with_statement", "function_definition",
    "class_definition", "decorated_definition", "raise_statement", "assert_statement",
    "import_statement", "import_from_statement", "pass_statement", "break_statement",
    "continue_statement", "delete_statement", "global_statement", "nonlocal_statement",
    "match_statement", "elif_clause", "else_clause", "except_clause", "finally_clause",
    "case_clause", "comment", "type_alias_statement", "print_statement", "exec_statement",
})


@dataclass(frozen=True)
class CodeChunk:
    text: str
    file: str            # path relative to the repo root, POSIX separators
    name: str            # "hello"
    qualified_name: str  # "Greeter.hello"
    type: str            # "function" | "method" | "class"
    start_line: int      # 1-based, inclusive (includes decorators)
    end_line: int        # 1-based, inclusive
    part: int = 1        # 1-based part number when a unit was split
    part_count: int = 1  # number of parts the unit was split into
    # True for every part of a split unit, including the single "own lines"
    # part of a large class whose body is all methods (part_count can be 1).
    split: bool = False

    @property
    def is_split(self) -> bool:
        return self.split or self.part_count > 1

    @property
    def embed_text(self) -> str:
        """Text sent to the embedding model.

        Whole units are embedded as-is (unchanged since Day 8, so existing
        vectors stay valid). Parts get a short header naming the unit they
        belong to, so a part from the middle of a function is still findable
        by that function's name.
        """
        if not self.is_split:
            return self.text
        name = self.qualified_name[:120]
        file = self.file[-60:]
        return f"# {file} :: {self.type} {name} (part {self.part}/{self.part_count})\n{self.text}"

    def to_dict(self) -> dict:
        data = asdict(self)
        if not self.is_split:
            # Keep the payload of unsplit chunks identical to the Day 8 format.
            del data["part"], data["part_count"], data["split"]
        return data


def _byte_len(text: str) -> int:
    return len(text.encode("utf-8"))


def _extract_text(source: bytes, node: Node) -> str:
    """Return the node's source, dedented so a method reads like a top-level def.

    Tree-sitter's node range starts at the `def`/`class`/decorator token, so the
    first line has lost its indentation while later lines keep theirs. We put the
    original indentation back on the first line, then dedent the whole block.
    """
    line_start = source.rfind(b"\n", 0, node.start_byte) + 1
    indent = source[line_start:node.start_byte]
    if indent.strip():  # code precedes the node on its line; nothing to restore
        indent = b""
    raw = (indent + source[node.start_byte:node.end_byte]).decode("utf-8", errors="replace")
    return textwrap.dedent(raw.replace("\r\n", "\n"))


def _statement_starts(node: Node, first: int, last: int, out: set[int]) -> None:
    """Collect 0-based rows in [first, last] where a statement/clause begins."""
    for child in node.children:
        if child.end_point[0] < first or child.start_point[0] > last:
            continue
        if child.type in _STATEMENT_TYPES and first <= child.start_point[0] <= last:
            out.add(child.start_point[0])
        _statement_starts(child, first, last, out)


def _split_line(line: str, budget: int) -> list[str]:
    """Cut one over-long line into pieces of at most `budget` bytes."""
    pieces: list[str] = []
    raw = line.encode("utf-8")
    while raw:
        cut = min(budget, len(raw))
        # Never cut inside a multi-byte character: back up to a lead byte.
        while cut < len(raw) and (raw[cut] & 0xC0) == 0x80:
            cut -= 1
        pieces.append(raw[:cut].decode("utf-8"))
        raw = raw[cut:]
    return pieces


def _pack_region(lines: list[str], first: int, last: int, breaks: set[int],
                 budget: int) -> list[tuple[int, int, str]]:
    """Greedily pack rows [first, last] into (start_row, end_row, text) parts.

    A part may end only right before a statement boundary (or at `last`), so
    parts stay syntactically meaningful. If no boundary fits the budget, fall
    back to whole lines; if one line alone is too long, cut it into byte windows.
    """
    parts: list[tuple[int, int, str]] = []
    start = first
    while start <= last:
        size = 0
        best_boundary = None
        best_line = None
        row = start
        while row <= last:
            size += _byte_len(lines[row]) + 1
            if size > budget:
                break
            best_line = row
            if row == last or (row + 1) in breaks:
                best_boundary = row
            row += 1

        end = best_boundary if best_boundary is not None else best_line
        if end is None:
            for piece in _split_line(lines[start], budget):
                parts.append((start, start, piece))
            start += 1
            continue
        parts.append((start, end, textwrap.dedent("\n".join(lines[start:end + 1]))))
        start = end + 1
    return parts


def _child_definition_rows(definition: Node) -> list[tuple[int, int]]:
    """Row ranges of methods / nested classes directly inside a class body."""
    body = definition.child_by_field_name("body")
    ranges: list[tuple[int, int]] = []
    if body is None:
        return ranges
    for child in body.children:
        inner = child.child_by_field_name("definition") if child.type == "decorated_definition" else child
        if inner is not None and inner.type in _DEFINITIONS:
            ranges.append((child.start_point[0], child.end_point[0]))
    return ranges


def _split_unit(unit: Node, definition: Node, source_lines: list[str], is_class: bool,
                file_path: str, name: str, qualified: str, kind: str) -> list[CodeChunk]:
    first, last = unit.start_point[0], unit.end_point[0]

    if is_class:
        # Only the class's own lines: methods/nested classes are chunked separately.
        regions: list[tuple[int, int]] = []
        cursor = first
        for child_first, child_last in _child_definition_rows(definition):
            if child_first > cursor:
                regions.append((cursor, child_first - 1))
            cursor = max(cursor, child_last + 1)
        if cursor <= last:
            regions.append((cursor, last))
        regions = [(a, b) for a, b in regions
                   if any(source_lines[r].strip() for r in range(a, b + 1))]
    else:
        regions = [(first, last)]

    breaks: set[int] = set()
    _statement_starts(unit, first, last, breaks)

    raw_parts: list[tuple[int, int, str]] = []
    for region_first, region_last in regions:
        # A region also "breaks" where it starts, regardless of syntax.
        raw_parts.extend(_pack_region(source_lines, region_first, region_last,
                                      breaks | {region_first}, MAX_PART_BYTES))

    total = len(raw_parts)
    return [
        CodeChunk(text=text, file=file_path, name=name, qualified_name=qualified, type=kind,
                  start_line=start + 1, end_line=end + 1, part=index, part_count=total, split=True)
        for index, (start, end, text) in enumerate(raw_parts, start=1)
    ]


def _collect(node: Node, source: bytes, source_lines: list[str], file_path: str,
             parent: str | None, chunks: list[CodeChunk]) -> None:
    for child in node.children:
        # `@decorator` + def are wrapped in a decorated_definition node; the span
        # we cut from the source must be the wrapper so decorators are included.
        definition = child
        if child.type == "decorated_definition":
            definition = child.child_by_field_name("definition")

        if definition is None or definition.type not in _DEFINITIONS:
            # Not a definition: look inside it (if/try/with blocks, class bodies...).
            _collect(child, source, source_lines, file_path, parent, chunks)
            continue

        name_node = definition.child_by_field_name("name")
        if name_node is None:  # only possible on badly broken syntax
            continue
        name = source[name_node.start_byte:name_node.end_byte].decode("utf-8", errors="replace")
        qualified = f"{parent}.{name}" if parent else name
        is_class = definition.type == "class_definition"
        kind = "class" if is_class else ("method" if parent else "function")

        text = _extract_text(source, child)
        if _byte_len(text) <= MAX_EMBED_BYTES:
            chunks.append(CodeChunk(
                text=text,
                file=file_path,
                name=name,
                qualified_name=qualified,
                type=kind,
                start_line=child.start_point[0] + 1,
                end_line=child.end_point[0] + 1,
            ))
        else:
            parts = _split_unit(child, definition, source_lines, is_class,
                                file_path, name, qualified, kind)
            logger.debug("Split %s %s in %s into %d parts", kind, qualified, file_path, len(parts))
            chunks.extend(parts)

        # Descend into classes to find their methods. Function bodies are NOT
        # descended into: nested functions stay inside the parent chunk.
        if is_class:
            _collect(definition, source, source_lines, file_path, qualified, chunks)


def chunk_source(source: bytes, file_path: str) -> list[CodeChunk]:
    """Chunk one Python file's bytes. `file_path` is stored as chunk metadata."""
    tree = Parser(PY_LANGUAGE).parse(source)
    if tree.root_node.has_error:
        # Tree-sitter recovers from syntax errors, so we still get every
        # definition it managed to parse.
        logger.warning("Syntax errors in %s; chunking the parseable parts", file_path)
    source_lines = source.decode("utf-8", errors="replace").replace("\r\n", "\n").split("\n")
    chunks: list[CodeChunk] = []
    _collect(tree.root_node, source, source_lines, file_path, None, chunks)
    return chunks


def _looks_generated(source: bytes) -> bool:
    head = source[:600].lower()
    return any(marker in head for marker in _GENERATED_MARKERS)


def chunk_file(file_path: Path, repo_root: Path) -> list[CodeChunk]:
    try:
        if file_path.stat().st_size > MAX_FILE_BYTES:
            logger.warning("Skipping %s: larger than %d bytes", file_path, MAX_FILE_BYTES)
            return []
        source = file_path.read_bytes()
    except OSError as exc:
        logger.warning("Skipping unreadable file %s: %s", file_path, exc)
        return []
    if _looks_generated(source):
        logger.info("Skipping generated file %s", file_path)
        return []
    return chunk_source(source, file_path.relative_to(repo_root).as_posix())


def is_backup_file(filename: str) -> bool:
    return bool(_BACKUP_FILE.search(filename))


def _is_indexable(filename: str) -> bool:
    if not filename.endswith(".py"):
        return False
    is_test_file = (
        filename.startswith("test_") or filename.endswith("_test.py") or filename == "conftest.py"
    )
    return not (is_test_file or is_backup_file(filename) or filename.endswith(_GENERATED_SUFFIXES))


def is_ignored_path(rel_path: str) -> bool:
    """True if a repo-relative POSIX path is excluded from indexing/review."""
    parts = rel_path.split("/")
    if any(p in IGNORED_DIRS or p.endswith(".egg-info") for p in parts[:-1]):
        return True
    if len(parts) >= 3 and parts[-3] == "alembic" and parts[-2] == "versions":
        return True
    return not _is_indexable(parts[-1])


def chunk_repository(repo_path: str | Path) -> list[CodeChunk]:
    """Chunk every indexable Python file under `repo_path`, in a stable order."""
    root = Path(repo_path).resolve()
    if not root.is_dir():
        raise NotADirectoryError(f"Not a directory: {root}")

    chunks: list[CodeChunk] = []
    for dirpath, dirnames, filenames in os.walk(root):  # symlinks are not followed
        dirnames[:] = sorted(
            d for d in dirnames if d not in IGNORED_DIRS and not d.endswith(".egg-info")
        )
        for filename in sorted(filenames):
            path = Path(dirpath) / filename
            if path.is_symlink():
                continue
            if not is_ignored_path(path.relative_to(root).as_posix()):
                chunks.extend(chunk_file(path, root))
    return chunks


def main() -> None:
    """Dev tool: python -m app.core.chunker <repo_path> [--show N]"""
    parser = argparse.ArgumentParser(description="Chunk a Python repository and print the result.")
    parser.add_argument("repo_path")
    parser.add_argument("--show", type=int, default=10, help="how many chunks to print (default 10)")
    args = parser.parse_args()

    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")
    chunks = chunk_repository(args.repo_path)

    by_type = Counter(c.type for c in chunks)
    split = sum(1 for c in chunks if c.is_split)
    print(f"{len(chunks)} chunks from {len({c.file for c in chunks})} files | "
          + ", ".join(f"{k}={v}" for k, v in sorted(by_type.items()))
          + f" | {split} split parts")

    for c in chunks[: args.show]:
        tag = f" part {c.part}/{c.part_count}" if c.is_split else ""
        print(f"\n--- {c.type} {c.qualified_name}{tag}  {c.file}:{c.start_line}-{c.end_line}"
              f"  ({_byte_len(c.text)} bytes)")
        lines = c.text.splitlines()
        print(textwrap.indent("\n".join(lines[:6]), "    "))
        if len(lines) > 6:
            print(f"    ... ({len(lines) - 6} more lines)")


if __name__ == "__main__":
    main()
